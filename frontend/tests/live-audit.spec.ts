import { expect, test } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";

// Opt-in: runs against the isolated audit server/database, never mocks API results.
test("真实后端：新建、保存、计算、PDF、修改失效、刷新与移动操作", async ({ page }) => {
  test.skip(process.env.STEEL_COMPASS_LIVE_AUDIT !== "1", "Requires isolated live audit backend");
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/login");
  await page.getByLabel("用户名").fill(process.env.AUDIT_USERNAME!);
  await page.getByLabel("密码", { exact: true }).fill(process.env.AUDIT_PASSWORD!);
  await page.getByRole("button", { name: "进入工作台" }).click();
  await expect(page.getByLabel("新项目名称")).toBeVisible();
  const name = `live-audit-${Date.now()}`;
  await page.getByLabel("新项目名称").fill(name);
  await page.getByRole("button", { name: "新建项目", exact: true }).click();
  await expect(page.getByLabel("保存到项目")).toHaveText(new RegExp(name));
  await page.getByRole("button", { name: "项目条件", exact: true }).click();
  await page.getByLabel("地区档").selectOption("zhejiang_coastal");
  await page.getByLabel("抗震设防烈度 / 加速度").selectOption("7_010g");
  await page.getByRole("button", { name: "保存项目模型", exact: true }).click();
  await expect(page.getByText(/旧分析结果已失效/)).toBeVisible();
  await page.screenshot({ path: "output/playwright/live-saved-desktop.png" });
  const analysisResponse = page.waitForResponse(r => r.url().endsWith("/analyze") && r.request().method() === "POST");
  await page.getByRole("button", { name: "完整分析", exact: true }).click();
  const response = await analysisResponse;
  expect(response.status()).toBe(200);
  const pdfLink = page.locator('a[href$="report.pdf"]');
  await expect(pdfLink).toHaveCount(1, { timeout: 20000 });
  const snapshot = await page.request.get((await pdfLink.getAttribute("href"))!.replace("/report.pdf", ""));
  expect(snapshot.status()).toBe(200);
  expect((await snapshot.json()).snapshot.custom_sections.length).toBeGreaterThan(0);
  const pdf = await page.request.get((await pdfLink.getAttribute("href"))!);
  expect(pdf.status()).toBe(200);
  expect((await pdf.body()).subarray(0, 4).toString()).toBe("%PDF");
  await mkdir("output/playwright", { recursive: true });
  await writeFile("output/playwright/live-report.pdf", await pdf.body());
  await page.screenshot({ path: "output/playwright/live-result-desktop.png" });
  await page.getByRole("button", { name: "项目条件", exact: true }).click();
  await page.getByLabel("地区档").selectOption("zhejiang_inland");
  await page.getByRole("button", { name: "结果", exact: true }).click();
  await expect(pdfLink).toHaveCount(0);
  await page.getByRole("button", { name: "保存项目模型", exact: true }).click();
  await expect(page.getByText(/旧分析结果已失效/)).toBeVisible();
  await page.reload();
  await page.getByLabel("保存到项目").selectOption({ label: name });
  await page.getByRole("button", { name: "项目条件", exact: true }).click();
  await expect(page.getByLabel("地区档")).toHaveValue("zhejiang_inland");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "项目条件", exact: true }).click();
  await expect(page.getByLabel("地区档")).toBeVisible();
  await page.screenshot({ path: "output/playwright/live-mobile.png" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
