// Generates frontend/lib/api-schema.ts from the committed backend OpenAPI
// snapshot (frontend/openapi/backend-openapi.json). No dependencies; the
// output is deterministic so CI can fail when the committed file is stale.
//
//   npm run gen:api            regenerate lib/api-schema.ts
//   npm run gen:api -- --check exit 1 if lib/api-schema.ts is out of date
//
// Refresh the snapshot itself with `npm run export:openapi` (needs the
// backend Python environment).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "openapi/backend-openapi.json");
const outputPath = resolve(root, "lib/api-schema.ts");

const spec = JSON.parse(readFileSync(schemaPath, "utf8"));
const schemas = spec.components?.schemas ?? {};

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const refName = (ref) => ref.replace("#/components/schemas/", "");
const literal = (value) => JSON.stringify(value);
const key = (name) => (IDENT.test(name) ? name : literal(name));

function union(parts) {
  const unique = [...new Set(parts)];
  return unique.length ? unique.join(" | ") : "unknown";
}

function typeOf(schema, indent) {
  if (!schema || schema === true) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.enum) return union(schema.enum.map(literal));
  if (schema.anyOf) return union(schema.anyOf.map((item) => wrap(typeOf(item, indent))));
  if (schema.oneOf) return union(schema.oneOf.map((item) => wrap(typeOf(item, indent))));
  if (schema.allOf) return schema.allOf.map((item) => wrap(typeOf(item, indent))).join(" & ");
  switch (schema.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      if (schema.prefixItems) return `[${schema.prefixItems.map((item) => typeOf(item, indent)).join(", ")}]`;
      return `${wrap(typeOf(schema.items, indent))}[]`;
    case "object":
      return objectType(schema, indent);
    default:
      if (Array.isArray(schema.type)) return union(schema.type.map((type) => typeOf({ ...schema, type }, indent)));
      return "unknown";
  }
}

function wrap(type) {
  return /[|&]/.test(type) && !/^[[{(]/.test(type) ? `(${type})` : type;
}

function objectType(schema, indent) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const names = Object.keys(properties);
  const extra = schema.additionalProperties;
  if (!names.length) {
    if (extra && extra !== true) return `Record<string, ${typeOf(extra, indent)}>`;
    return "Record<string, unknown>";
  }
  const inner = `${indent}  `;
  const lines = names.map((name) => `${inner}${key(name)}${required.has(name) ? "" : "?"}: ${typeOf(properties[name], inner)};`);
  if (extra && extra !== true) lines.push(`${inner}[key: string]: ${typeOf(extra, inner)} | undefined;`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function comment(schema) {
  const text = (schema.description ?? "").trim();
  if (!text) return "";
  return `/**\n${text.split("\n").map((line) => ` * ${line}`.trimEnd()).join("\n")}\n */\n`;
}

const names = Object.keys(schemas).sort();
const body = names
  .map((name) => {
    const schema = schemas[name];
    const type = typeOf(schema, "");
    const declaration =
      schema.type === "object" && type.startsWith("{") ? `export interface ${name} ${type}` : `export type ${name} = ${type};`;
    return comment(schema) + declaration;
  })
  .join("\n\n");

const output = `// Generated by scripts/gen-api.mjs from openapi/backend-openapi.json
// (${spec.info?.title ?? "API"} ${spec.info?.version ?? ""}). Do not edit; run \`npm run gen:api\`.
/* eslint-disable */

${body}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // missing file counts as stale
  }
  if (current !== output) {
    console.error("lib/api-schema.ts is out of date with openapi/backend-openapi.json; run `npm run gen:api`.");
    process.exit(1);
  }
  console.log("lib/api-schema.ts is up to date.");
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${names.length} schemas to lib/api-schema.ts`);
}
